def _g3(ch):
    return FONT3.get(ch) or FONT3.get(ch.upper()) or FONT3['?']


def text3_width(s, gap=1):
    return sum(len(_g3(ch)[0]) + gap for ch in s) - gap if s else 0


def text3(L, x, y, s, c, emit=False, vertical=False, gap=1):
    """3x5 text, one letter per column or (vertical) per row."""
    cx, cy = x, y
    for ch in s:
        glyph = _g3(ch)
        for j, row in enumerate(glyph):
            for i, v in enumerate(row):
                if v == '#':
                    L.set(cx + i, cy + j, c, emit)
        if vertical:
            cy += 6
        else:
            cx += len(glyph[0]) + gap


